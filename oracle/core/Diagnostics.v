(* What the checker finds: refusals, and the places where Ralph has to stop with `NotBuiltYet` or `NotDesignedYet`.

   Each one is data: what went wrong, where, and the names, types and places a message needs. The shell words them,
   in D54's layout with the wordings the decisions give (D85, D87, D88, D89, D92, D102, D103, D117, D120, D121,
   D132, D161). *)

From Stdlib Require Import String List.
From Ralph Require Import Syntax.

Inductive refusal :=
(* Variables and names *)
(* trace: D92, D93, D102 — the place it was declared, when it was declared inside a block that has ended *)
| Unknown_variable (name : string) (at_ : place) (ended_at : option place)
(* trace: D94, D102 *)
| Name_in_use (name : string) (at_ first_at : place)
(* trace: D14, D85, D87 *)
| Let_cannot_change (name : string) (at_ keyword_at : place)
(* trace: D147: a parameter is read-only, like a `let` *)
| Parameter_cannot_change (name : string) (at_ parameter_at : place)
(* trace: D102, D126 *)
| Two_parameters_one_name (name : string) (at_ : place)
(* Types *)
(* trace: D92: `$x` is a `Whole`, but this value is a `Text` *)
| Wrong_value_type (name : string) (expected found : type) (at_ : place)
(* trace: D92: `f` takes a `Whole` here, but this is a `Text` *)
| Argument_type (procedure : string) (expected found : type) (at_ : place)
(* trace: D89: `f` takes a `Whole` first, but the slid value is a `Text` *)
| Slid_value_type (procedure : string) (expected found : type) (at_ : place)
(* trace: D89: the call gives a `Whole`, so the value after `??` must be one too, not a `Text` *)
| Fallback_type (expected found : type) (at_ : place)
(* trace: D17, D87, D89 *)
| Compare_types (operator : binary_operator) (left right : type) (at_ : place)
(* trace: D27, D59, D89 *)
| Arithmetic_types (operator : binary_operator) (left right : type) (at_ : place)
(* trace: D27, D28, D87, D201: `+` on two texts, fixed by filling in one text with braces when both sides allow it *)
| Plus_on_text (operator_at : place) (left right : expression)
(* trace: D27, D89 *)
| Negate_non_number (found : type) (at_ : place)
(* trace: D22, D87 *)
| Convert_to_same (target : type) (at_ : place)
(* Narrowings *)
(* trace: D22, D87 *)
| Be_without_type (at_ : place)
(* trace: D102, D103: the word as written, the narrowing, and the word's narrowings, none for a plain word *)
| Unknown_narrowing (word : string) (narrowing : string) (at_ : place) (narrowings : list string)
(* trace: D103: a word that's already a narrowing, like `be.Whole`, can't be narrowed further *)
| Narrowing_on_narrowed (word : string) (narrowing : string) (at_ : place)
(* trace: D102 *)
| Narrowing_twice (narrowing : string) (at_ : place)
(* Calls *)
(* trace: D92 *)
| Unknown_procedure (name : string) (at_ : place)
(* trace: D92: a variable's name written as a call *)
| Variable_called (name : string) (at_ : place)
(* trace: D94, D102, D192: a variable or parameter with a procedure's name; the procedure's place, if it's the
   program's own *)
| Name_is_procedure (name : string) (at_ : place) (procedure_at : option place)
(* trace: D4, D92 *)
| Procedure_without_brackets (name : string) (at_ : place)
(* trace: D38, D88 *)
| Gives_nothing_used (at_ : place)
(* trace: D120 *)
| Value_unused (procedure : string) (given : type) (at_ : place)
(* trace: D23, D87 *)
| Failure_unhandled (at_ : place)
(* trace: D81, D102 *)
| Fallback_without_failing_call (at_ : place)
(* trace: D24, D88: fixed by writing the label in front of the value *)
| Missing_label (label : string) (value_at : place)
(* trace: D24, D88: fixed by taking the label away; the label's place and the value's *)
| Label_where_none (label_at value_at : place)
(* trace: D24, D88 *)
| Wrong_label (expected found : string) (at_ : place)
(* trace: D24, D88, D89: the place it's declared, if the program declares it *)
| Argument_count (procedure : string) (expected given : nat) (at_ : place) (declared_at : option place)
(* Text's braces *)
(* trace: D29, D92, D200 *)
| Brace_not_variable (name : string) (at_ : place)
(* trace: D29, D92, D200 *)
| Brace_calculation (at_ : place)
(* trace: D175: `places:` on anything but a `Float` *)
| Places_on_non_float (name : string) (found : type) (at_ : place)
(* trace: D187: a condition that isn't a `Bool`, fixed with `not_eq 0` for a `Whole` *)
| Condition_not_bool (found : type) (at_ : place)
(* `return`, `break` and what may follow them *)
(* trace: D38, D57, D88 *)
| Return_value_without_returns (procedure : string) (at_ : place)
(* trace: D57, D88 *)
| Bare_return_with_returns (procedure : string) (expected : type) (at_ : place)
(* trace: D57, D88 *)
| Missing_return (procedure : string) (expected : type) (at_ : place)
(* trace: D57, D88, D117: after a `return` when [by_return], otherwise after a `break` *)
| After_leaving (by_return : bool) (at_ leave_at : place)
(* trace: D57, D88 *)
| Bare_return_last (at_ : place)
(* trace: D9, D88 *)
| After_if_that_leaves (at_ if_at : place)
(* trace: D32, D88 *)
| Break_outside_loop (at_ : place)
(* `labels` lines *)
(* trace: D25, D89 *)
| Labels_not_first (at_ : place)
(* trace: D25, D89 *)
| Label_for_missing_parameter (procedure : string) (name : string) (at_ : place)
(* trace: D25, D89 *)
| Two_labels_one_parameter (name : string) (at_ : place)
(* trace: D25, D89 *)
| One_label_two_parameters (label : string) (at_ : place)
(* Slides (D128, D142): the whole expression is given, for the shell to write the fix from. *)
(* trace: D128, D142: one or two calls written as a slide, fixed by writing them as calls *)
| Slide_as_calls (whole : expression)
(* trace: D128, D142: three or more calls nested, or mixing calls and a slide, fixed by writing one slide *)
| Calls_as_slide (whole : expression)
(* trace: D160: `random` with plain numbers, `from:` above `to:`; fixed by swapping them *)
| Random_backwards_plain (at_ from_at to_at : place)
(* trace: D161: a line that only works out a value *)
| Value_only_line (at_ : place) (given : type)
(* trace: D161: `not` on something that isn't a `Bool` *)
| Not_on_non_bool (found : type) (at_ : place)
(* trace: D161: `and` or `or` on something that isn't a `Bool` *)
| Logic_on_non_bool (operator : binary_operator) (found : type) (at_ : place)
(* A program's shape *)
(* trace: D64, D92 *)
| Two_mains (at_ first_at : place)
(* trace: D64, D92 *)
| Two_procedures_one_name (name : string) (at_ first_at : place)
(* trace: D64, D92 *)
| No_main.

(* What isn't decided yet, so Ralph stops with `NotDesignedYet` (D56, D103). *)
Inductive not_designed :=
| Whole_literal_out_of_range     (* how whole numbers are written, and going past the range (D15) *)
| Comparing_text                 (* comparing two pieces of text (D17, D21) *)
| Ordering_bools                 (* `<`, `>`, `at_least` and `at_most` on `Bool`s (D17, D33) *)
| Converting                     (* what may be converted to what (D22) *)
| Format_unclosed                (* a `{` that's never closed in text (D29, D30) *)
| Bare_word_not_procedure        (* a narrowed word with no `( )` that isn't a procedure *)
| Library_name_taken             (* a procedure with the name of one of the library's *)
| Label_order                    (* labels in a different order from the parameters (D24, D25) *)
| Return_type_wording            (* the message for `return` giving a value of the wrong type (D57) *)
| Main_returns.                  (* `proc.main` with `->` (D4, D37) *)

Inductive diagnostic :=
| Refused (what : refusal)
| Not_designed_yet (what : not_designed) (at_ : place)
(* Something decided but not built yet in Ralph (D56), with the decisions that decided it, as D103 words it. *)
| Not_built_yet (what : string) (at_ : place)
(* A part the parser has already refused: nothing more is said about it (D55). *)
| Already_refused (at_ : place)
(* The checker accepted a program whose typed tree the second type checker refuses (TypedTree.v): a bug in Ralph,
   never the program's mistake, so it's an internal error (D82). *)
| Typed_tree_refused.
